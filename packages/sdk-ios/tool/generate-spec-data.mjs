// Generates Sources/GiftingStack/Core/SpecData.generated.swift from packages/sdk-spec/recipes.json.
//
//   node packages/sdk-ios/tool/generate-spec-data.mjs          write the Swift file
//   node packages/sdk-ios/tool/generate-spec-data.mjs --check  exit 1 if the file is stale
//
// Any key the generator does not know makes it fail, so a new shared number cannot be skipped.
// RecipesDriftTests (Swift) compares the result with recipes.json field by field as well.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specFile = join(here, "..", "..", "sdk-spec", "recipes.json");
const outFile = join(here, "..", "Sources", "GiftingStack", "Core", "SpecData.generated.swift");

const TIERS = ["small", "medium", "large"];
const QUALITIES = ["high", "low"];
const STAGES = { "float-up": ".floatUp", center: ".center" };
// Field order of the Swift EffectRecipe initializer, with the Swift kind of each field.
const RECIPE_FIELDS = [
  ["tier", "tier"],
  ["peakScale", "double"],
  ["flyInMs", "int"],
  ["holdMs", "int"],
  ["flyOutMs", "int"],
  ["stage", "stage"],
  ["sparks", "int"],
  ["sparkSpread", "double"],
  ["coins", "int"],
  ["dim", "bool"],
  ["rays", "bool"],
  ["noticeMs", "int"],
  ["noticeBig", "bool"],
];
const TOP_KEYS = [
  "specVersion",
  "thresholds",
  "comboWindowMs",
  "maxConcurrentEffects",
  "maxQueuedLarge",
  "defaultSenderName",
  "recipes",
];

function fail(message) {
  process.stderr.write(`generate-spec-data: ${message}\n`);
  process.exit(1);
}

function sameKeys(obj, keys, where) {
  if (obj === null || typeof obj !== "object" || Array.isArray(obj))
    fail(`${where} is not an object`);
  const got = Object.keys(obj).sort();
  const want = [...keys].sort();
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    fail(`${where} has keys ${JSON.stringify(got)}, expected ${JSON.stringify(want)}`);
  }
}

function int(value, where) {
  if (!Number.isInteger(value)) fail(`${where} must be an integer, got ${JSON.stringify(value)}`);
  return String(value);
}

function double(value, where) {
  if (typeof value !== "number" || !Number.isFinite(value)) fail(`${where} must be a number`);
  return String(value);
}

function bool(value, where) {
  if (typeof value !== "boolean") fail(`${where} must be a boolean`);
  return String(value);
}

function swiftString(value, where) {
  if (typeof value !== "string") fail(`${where} must be a string`);
  let out = '"';
  for (const ch of value) {
    const code = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

function recipeLiteral(recipe, tier, where) {
  sameKeys(
    recipe,
    RECIPE_FIELDS.map(([k]) => k),
    where,
  );
  const args = RECIPE_FIELDS.map(([key, kind]) => {
    const v = recipe[key];
    const at = `${where}.${key}`;
    switch (kind) {
      case "tier":
        if (v !== tier) fail(`${at} is ${JSON.stringify(v)}, expected "${tier}"`);
        return `${key}: .${tier}`;
      case "stage":
        if (!(v in STAGES)) fail(`${at} is an unknown stage ${JSON.stringify(v)}`);
        return `${key}: ${STAGES[v]}`;
      case "int":
        return `${key}: ${int(v, at)}`;
      case "double":
        return `${key}: ${double(v, at)}`;
      case "bool":
        return `${key}: ${bool(v, at)}`;
      default:
        return fail(`unknown kind ${kind}`);
    }
  });
  return `EffectRecipe(\n                ${args.join(",\n                ")}\n            )`;
}

export function generate(spec) {
  sameKeys(spec, TOP_KEYS, "recipes.json");
  sameKeys(spec.thresholds, ["mediumFrom", "largeFrom"], "thresholds");
  sameKeys(spec.maxConcurrentEffects, TIERS, "maxConcurrentEffects");
  sameKeys(spec.recipes, QUALITIES, "recipes");

  const cases = [];
  for (const quality of QUALITIES) {
    sameKeys(spec.recipes[quality], TIERS, `recipes.${quality}`);
    for (const tier of TIERS) {
      const literal = recipeLiteral(
        spec.recipes[quality][tier],
        tier,
        `recipes.${quality}.${tier}`,
      );
      cases.push(`        case (.${quality}, .${tier}):\n            return ${literal}`);
    }
  }

  return `// Generated by tool/generate-spec-data.mjs from packages/sdk-spec/recipes.json.
// Do not edit by hand. Regenerate: node packages/sdk-ios/tool/generate-spec-data.mjs
// RecipesDriftTests fails when this file and recipes.json disagree.

/// The numbers every GiftingStack SDK shares (\`packages/sdk-spec/recipes.json\`).
public enum GiftingSpec {
    /// The spec version these numbers and the conformance fixtures belong to.
    public static let specVersion: String = ${swiftString(spec.specVersion, "specVersion")}
    public static let defaultMediumFrom: Int = ${int(spec.thresholds.mediumFrom, "thresholds.mediumFrom")}
    public static let defaultLargeFrom: Int = ${int(spec.thresholds.largeFrom, "thresholds.largeFrom")}
    public static let comboWindowMs: Int = ${int(spec.comboWindowMs, "comboWindowMs")}
    public static let maxConcurrentSmall: Int = ${int(spec.maxConcurrentEffects.small, "maxConcurrentEffects.small")}
    public static let maxConcurrentMedium: Int = ${int(spec.maxConcurrentEffects.medium, "maxConcurrentEffects.medium")}
    public static let maxConcurrentLarge: Int = ${int(spec.maxConcurrentEffects.large, "maxConcurrentEffects.large")}
    public static let maxQueuedLarge: Int = ${int(spec.maxQueuedLarge, "maxQueuedLarge")}
    public static let defaultSenderName: String = ${swiftString(spec.defaultSenderName, "defaultSenderName")}

    /// The recipe table exactly as \`recipes.json\` lists it. \`recipeFor\` derives the low
    /// recipes from the high ones like the reference; a test checks that both agree.
    public static func specRecipe(_ tier: EffectTier, quality: EffectQuality) -> EffectRecipe {
        switch (quality, tier) {
${cases.join("\n")}
        }
    }
}
`;
}

const spec = JSON.parse(readFileSync(specFile, "utf8"));
const swift = generate(spec);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
  } catch {
    fail(`${outFile} is missing`);
  }
  if (current !== swift)
    fail(`${outFile} is stale: run node packages/sdk-ios/tool/generate-spec-data.mjs`);
  process.stdout.write("SpecData.generated.swift is up to date\n");
} else {
  writeFileSync(outFile, swift);
  process.stdout.write(`wrote ${outFile}\n`);
}
