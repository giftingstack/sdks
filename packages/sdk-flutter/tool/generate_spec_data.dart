// Generates lib/src/core/spec_data.g.dart from ../sdk-spec/recipes.json.
//
//   dart run tool/generate_spec_data.dart          (run from packages/sdk-flutter)
//   dart run tool/generate_spec_data.dart --check  (exit 1 when the file drifted)
//
// Pure Dart, no packages: the drift test in test/spec_data_test.dart imports
// [generateSpecData] and compares its output with the committed file.
import 'dart:convert';
import 'dart:io';

const String recipesPath = '../sdk-spec/recipes.json';
const String outputPath = 'lib/src/core/spec_data.g.dart';

String _num(Object? v) {
  if (v is int) return '$v';
  if (v is double) return v == v.roundToDouble() ? v.toStringAsFixed(1) : '$v';
  throw FormatException('Expected a number, got $v');
}

String _double(Object? v) => _num((v as num).toDouble());

String _recipe(String name, Map<String, Object?> r) {
  final stage = r['stage'] == 'float-up' ? 'floatUp' : 'center';
  return '''
const EffectRecipe $name = EffectRecipe(
  tier: EffectTier.${r['tier']},
  peakScale: ${_double(r['peakScale'])},
  flyInMs: ${_num(r['flyInMs'])},
  holdMs: ${_num(r['holdMs'])},
  flyOutMs: ${_num(r['flyOutMs'])},
  stage: EffectStage.$stage,
  sparks: ${_num(r['sparks'])},
  sparkSpread: ${_num(r['sparkSpread'])},
  coins: ${_num(r['coins'])},
  dim: ${r['dim']},
  rays: ${r['rays']},
  noticeMs: ${_num(r['noticeMs'])},
  noticeBig: ${r['noticeBig']},
);
''';
}

/// The text of the generated file for the given `recipes.json` text.
String generateSpecData(String recipesJson) {
  final spec = jsonDecode(recipesJson) as Map<String, Object?>;
  final thresholds = spec['thresholds'] as Map<String, Object?>;
  final caps = spec['maxConcurrentEffects'] as Map<String, Object?>;
  final high =
      (spec['recipes'] as Map<String, Object?>)['high'] as Map<String, Object?>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_spec_data.dart from')
    ..writeln('// packages/sdk-spec/recipes.json. Do not edit by hand.')
    ..writeln('// dart format off')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln()
    ..writeln("import 'effect_recipe.dart';")
    ..writeln()
    ..writeln("const String kSpecVersion = '${spec['specVersion']}';")
    ..writeln('const int kMediumFrom = ${_num(thresholds['mediumFrom'])};')
    ..writeln('const int kLargeFrom = ${_num(thresholds['largeFrom'])};')
    ..writeln('const int kComboWindowMs = ${_num(spec['comboWindowMs'])};')
    ..writeln('const int kMaxConcurrentSmall = ${_num(caps['small'])};')
    ..writeln('const int kMaxConcurrentMedium = ${_num(caps['medium'])};')
    ..writeln('const int kMaxConcurrentLarge = ${_num(caps['large'])};')
    ..writeln('const int kMaxQueuedLarge = ${_num(spec['maxQueuedLarge'])};')
    ..writeln(
      "const String kDefaultSenderName = '${spec['defaultSenderName']}';",
    )
    ..writeln();
  for (final tier in const ['small', 'medium', 'large']) {
    final name = 'kHigh${tier[0].toUpperCase()}${tier.substring(1)}';
    b
      ..write(_recipe(name, high[tier]! as Map<String, Object?>))
      ..writeln();
  }
  b
    ..writeln(
        'const Map<EffectTier, EffectRecipe> kHighRecipes = <EffectTier, EffectRecipe>{')
    ..writeln('  EffectTier.small: kHighSmall,')
    ..writeln('  EffectTier.medium: kHighMedium,')
    ..writeln('  EffectTier.large: kHighLarge,')
    ..writeln('};');
  return b.toString();
}

void main(List<String> args) {
  final source = File(recipesPath);
  if (!source.existsSync()) {
    stderr.writeln('Missing $recipesPath. Run from packages/sdk-flutter.');
    exit(2);
  }
  final text = generateSpecData(source.readAsStringSync());
  final out = File(outputPath);
  if (args.contains('--check')) {
    final current =
        out.existsSync() ? out.readAsStringSync().replaceAll('\r\n', '\n') : '';
    if (current != text) {
      stderr.writeln(
        '$outputPath is out of date. Run: dart run tool/generate_spec_data.dart',
      );
      exit(1);
    }
    return;
  }
  out.writeAsStringSync(text);
  stdout.writeln('Wrote $outputPath');
}
